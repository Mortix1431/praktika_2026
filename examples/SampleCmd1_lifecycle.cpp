#include "StdAfx.h"
#include "Commands.h"

// Глобальный указатель на единственный экземпляр команды
SampleCmd1* gpCmd1 = NULL;

//===========================================================
// Конструктор: имя команды + флаги регистрации (см. command_flags_constants.md)
SampleCmd1::SampleCmd1()
	: mcsCmd(NULL, _T("lm_cmd1"), MCS_CMD_DEBUG | MCS_CMD_REDRAW | MCS_CMD_NO_PREFIX)
{
}
//===========================================================

// Тело команды
HRESULT SampleCmd1::Execute(MCSVariant* pCustomParams)
{
	return S_OK;
}
//===========================================================

// Регистрация: создать экземпляр (если нет) и зарегистрировать в контексте
void SampleCmd1::Register()
{
	if(!gpCmd1)
	{
		gpCmd1 = new SampleCmd1();
		gpMcContext->RegisterCommand(*gpCmd1);
	}
}
//===========================================================

// Выгрузка: удалить экземпляр и ОБНУЛИТЬ указатель.
// (!) Частая ошибка — вместо обнуления заново создать команду. Правильно — NULL.
void SampleCmd1::Unregister()
{
	if(gpCmd1)
	{
		delete gpCmd1;
		gpCmd1 = NULL;
	}
}
//===========================================================
