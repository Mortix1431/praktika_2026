// Команда test_SmCircle создаёт в текущем документе окружность (радиус 300,
// центр (500,500,0)) и красит её в зелёный. Готова к вставке в SmTests.cpp.
//
// Стиль — по корпоративному стандарту (docs/coding_standard.md):
//   * проверка указателей перед обращением (п.5.k);
//   * без исключений — коды возврата (п.5.a.i);
//   * умные указатели вместо new/delete (п.5.e);
//   * без STL; табы; комментарии-разделители на русском (п.4).
//
// Используются только подтверждённые методы API (createObject, setRadius,
// Entity, addToDocument, transform, setColor, update) — центр задаётся
// переносом из начала координат, чтобы не зависеть от наличия setCenter.
//
// (!) Точное имя GUID класса CLSID_IMcCircle сверить в IMcStdObjects.h
//     (рядом с CLSID_IMcLine; в Visual Studio — автодополнение по "CLSID_IMc").
//==================================================================================================

//==================================================================================================
// Команда test_SmCircle: создать окружность и подсветить зелёным.
//==================================================================================================
void cmdTest_SmCircle(MCSVariant*)
{
	// создаём новый объект-окружность
	IMcCirclePtr pCircle = gpMcObjManager->createObject(CLSID_IMcCircle);
	if (!pCircle)                                     // проверка указателя (п.5.k)
		return;

	// задаём радиус окружности
	pCircle->setRadius(300.0);

	// берём сущность чертежа этой окружности
	IMcDbEntityPtr pCircDBE = pCircle->Entity();
	if (!pCircDBE)
		return;

	// помещаем окружность в текущий документ
	if (FAILED(gpMcObjManager->addToDocument(pCircDBE)))
		return;

	// переносим из начала координат в центр (500,500,0) и красим в зелёный
	mcsMatrix tfmToCenter = mcsMatrix::translation(mcsVector(500, 500, 0));
	pCircDBE->transform(tfmToCenter);
	pCircDBE->setColor(GREEN);

	pCircDBE->update();                               // применить изменения
}

