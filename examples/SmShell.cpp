//==================================================================================================
//	Автотест построения «Обечайки» (линейчатое тело) — по образцу cmdTest_SmHole.
//	Открыть документ-шаблон "SmShell_TemplateTest.dwg".
//
//	handle'ы из шаблона (Entity Monitor / _LIST):
//	    источник (прямоугольник) = 0x7A5
//	    эталон (обечайка)        = 0x68D
//	    построенная обечайка     = 0x8EB
//
//	(!) Имя команды: обечайка = линейчатое тело -> SmCmd::Ruled.
//	    Если не компилируется — сверь точное имя по SmRuled.cpp.
//==================================================================================================
void cmdTest_SmShell(MCSVariant*)
{
	NO_SM_DIALOGS;					//	команда идёт из строки ввода, без диалогов

	setTestToolResValue(true);		//	по умолчанию тест считаем пройденным

	McsString strPt, strCmdInput;

	//	точка на источнике (центр контура) — «по точке»
	strPt = getStrCenterPoint(0x7A5);

	//	эмуляция кликов: выбрать источник (obj) + ткнуть точку (pt) + дважды «Готово»
	strCmdInput.Format(_T("obj=0x%x,pt=%s cmdid=%d cmdid=%d"),
		0x7A5, strPt,
		SmCmd::command_finish,
		SmCmd::command_finish
	);

	//	запуск команды обечайки (= линейчатое тело)
	gpMcContext->TestExecuteCommand(SmCmd::Ruled.asT(), strCmdInput);	//	сверь имя по SmRuled.cpp

	//	сверка построенной обечайки (0x8EB) с эталоном (0x68D)
	if (!compareSolids(0x68D, 0x8EB))
		setTestToolResValue(false);
}
